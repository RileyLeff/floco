// MACRO: constrained_type! (The public-facing macro)
// =================================================================================
//

/// A macro to create new, validated types that wrap a primitive or other value.
#[macro_export]
macro_rules! constrained_type {
    // ARM 1: User provides an explicit default value.
    ($(#[$outer:meta])* $vis:vis type $TypeName:ident($InnerType:ty) where |$val_id:ident| $validator:expr, $error_msg:expr, default: $default_val:expr) => {
        $crate::__floco_internal_newtype_impl!{
            $(#[$outer])*,
            $vis,
            $TypeName,
            $InnerType,
            |$val_id| $validator,
            $error_msg
        }

        #[cfg(not(feature = "runtime-defaults"))]
        const _: () = {
            const fn check($val_id: $InnerType) -> bool { $validator }
            if !check($default_val) {
                 panic!(concat!("The provided default value for `", stringify!($TypeName), "` does not meet the constraint criteria."));
            }
        };

        impl Default for $TypeName {
            fn default() -> Self {
                Self::try_new($default_val).expect("The provided default value is invalid.")
            }
        }
    };

    // ARM 2: No default value is provided.
    ($(#[$outer:meta])* $vis:vis type $TypeName:ident($InnerType:ty) where |$val_id:ident| $validator:expr, $error_msg:expr) => {
        $crate::__floco_internal_newtype_impl!{
            $(#[$outer])*,
            $vis,
            $TypeName,
            $InnerType,
            |$val_id| $validator,
            $error_msg
        }

        #[cfg(not(feature = "runtime-defaults"))]
        const _: () = {
            const fn check($val_id: $InnerType) -> bool { $validator }
            if !check(<$InnerType as Default>::default()) {
                 panic!(concat!("The default value from `", stringify!($InnerType), "` does not meet the constraint criteria for `", stringify!($TypeName), "`."));
            }
        };

        impl Default for $TypeName where $InnerType: Default {
            fn default() -> Self {
                Self::try_new(<$InnerType as Default>::default()).expect("The inner type's default value is invalid.")
            }
        }
    };
}

